// Memperbarui status atau nama pet menggunakan petId yang tersimpan di GlobalVariable
def response = WS.sendRequest(findTestObject('Object Repository/API/Petstore/PUT_Pet', [('petId') : GlobalVariable.petId]))

// Assertion Status Code
WS.verifyResponseStatusCode(response, 200)

// Parse dan Assertion Response Body hasil update
def jsonSlurper = new JsonSlurper()
def jsonResponse = jsonSlurper.parseText(response.getResponseText())

assert jsonResponse.id == GlobalVariable.petId : "ID Pet tidak cocok"
assert jsonResponse.status == "sold" : "Status pet gagal diperbarui menjadi sold"
println("Successfully updated Pet ID: " + GlobalVariable.petId)